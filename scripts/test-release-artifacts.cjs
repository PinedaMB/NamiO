const assert = require('node:assert/strict')
const fs = require('node:fs')
const { createRequire } = require('node:module')
const builderRequire = createRequire(require.resolve('electron-builder'))
const appBuilderRequire = createRequire(builderRequire.resolve('app-builder-lib'))
const { load } = appBuilderRequire('js-yaml')
builderRequire('app-builder-lib')
const { computeSafeArtifactNameIfNeeded } = appBuilderRequire('./platformPackager')
const config = load(fs.readFileSync('electron-builder.yml', 'utf8'))
const manifest = JSON.parse(fs.readFileSync('package.json', 'utf8'))
const filename = config.nsis.artifactName.replace(/\$\{(productName|version|ext)\}/g, (_, key) => ({ productName: manifest.productName, version: manifest.version, ext: 'exe' })[key])
assert.match(filename, /^[a-zA-Z0-9._-]+\.exe$/, 'GitHub upload must preserve the installer filename')
assert.equal(computeSafeArtifactNameIfNeeded(filename, () => 'different-safe-name.exe'), null, 'electron-builder must use the actual installer name in update metadata')
console.log('Windows release: installer filename is preserved by GitHub and update metadata')
